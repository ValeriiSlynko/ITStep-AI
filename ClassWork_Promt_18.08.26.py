import os
import dotenv
import langchain
from langchain_google_genai import GoogleGenerativeAI
import langchain_google_genai
from langchain_core.prompts import PromptTemplate

from lesson2 import response

# завантаження даних з файлу .env
dotenv.load_dotenv()

# сам api key
api_key = os.getenv('GEMINI_API_KEY')

llm = GoogleGenerativeAI(
    model='gemini-3.5-flash-lite',   # назва моделі
    api_key=api_key,
    temperature=0.5
)
prompt = PromptTemplate.from_template ("""
    Ти - асистент програміст
    Задача: згенерувати код на {prog_lang} для вирішення задачі
    
    ###ПРАВИЛА###
    1. Пиши тільки код
    2. Пиши простий код з посиланнями для початківця
    3. Розпиши максимально детально з поясненням кожного рядка коду
    
    ###ПРИКЛАДИ###
    
    ###ОПИС ЗАДАЧІ###
    {customer_task}
""")

prog_lang = "python"
customer_task = "simple calculator, +/-"

data = {
    "prog_lang": "python",
    "customer_task": customer_task,
}
text = prompt.invoke(data)

response = llm.invoke(text)
print(response)

