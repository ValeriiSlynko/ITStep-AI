# --- Реалізація Zero-shot ---
prompt_zero_shot = PromptTemplate.from_template("""
Ти - редактор тексту.
Задача: переводити тексти з неформального стилю в формальний.

###ВИМОГИ###
1. Повинен бути збережений основний зміст з оригінального тексту.
2. Відповідь не перевищує 3-4 речень.
3. Виправ всі граматичні, орфографічні помилки та знаки пунктуації.

###ПАРАМЕТРИ###
Текст: {text}

Формальний варіант:
""")

input_text = "Надрукуй мені шпаргалку по всім основам вивчення Пайтону і все, що зним"

# Передаємо дані у промпт
text_zero_shot = prompt_zero_shot.invoke({"text": input_text})
